program gen_hpd_leaves
    ! Complex arithmetic is represented by real/imaginary components.
    ! JVP/VJP use the real Euclidean pairing on those components.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(-), &
                            operator(*), operator(/)
    use fortsym_diff, only: diff
    use fortsym_string, only: str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel, TARGET_FORTRAN_CPU
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    implicit none
    character(*), parameter :: revision = &
                               '7e8ef7abdd90c49bb5f75e2c119e7d181656bcc6'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: x(6), dx(6), seeds(2), f(2)
    integer :: u, t, k, ios
    character(512) :: line
    character(2) :: index

    call arena%init()
    engine = make_native_engine(arena)
    do k = 1, 6
        write (index, '(i0)') k
        x(k) = sym(arena, 'x'//trim(index))
        dx(k) = sym(arena, 'dx'//trim(index))
    end do
    seeds(1) = sym(arena, 's1')
    seeds(2) = sym(arena, 's2')
    open (newunit=u, file='src/generated/fortsparse_hpd_leaves.f90', &
          status='replace', action='write')
    write (u, '(a)') '! Generated by gen/gen_hpd_leaves.f90; DO NOT EDIT.'
    write (u, '(a)') '! FortSym '//revision
    write (u, '(a)') 'module fortsparse_hpd_leaves'
    write (u, '(a)') '    use, intrinsic :: iso_fortran_env, only: dp => real64'
    write (u, '(a)') '    implicit none'
    write (u, '(a)') 'contains'
    call leaf('root', [sqrt(x(1))], 1)
    call leaf('divide', [x(1)/x(3), x(2)/x(3)], 3)
    f(1) = x(1) - x(3)*x(5) + x(4)*x(6)
    f(2) = x(2) - x(3)*x(6) - x(4)*x(5)
    call leaf('update', f, 6)
    f(1) = x(1) - x(3)*x(5) - x(4)*x(6)
    f(2) = x(2) + x(3)*x(6) - x(4)*x(5)
    call leaf('conj_update', f, 6)
    call leaf('norm_update', [x(1) - x(2)*x(2) - x(3)*x(3)], 3)
    open (newunit=t, file='gen/hpd_schedule.f90.inc', action='read')
    do
        read (t, '(a)', iostat=ios) line
        if (ios /= 0) exit
        write (u, '(a)') trim(line)
    end do
    close (t)
    write (u, '(a)') 'end module fortsparse_hpd_leaves'
    close (u)
contains
    subroutine leaf(name, values, n)
        character(*), intent(in) :: name
        type(expr_t), intent(in) :: values(:)
        integer, intent(in) :: n
        type(kernel_spec_t) :: spec
        type(expr_t) :: roots(2*size(values)), gradient(n, size(values))
        type(expr_t) :: vjp(n + size(values)), tangent
        integer :: i, j, m
        character(2) :: s

        m = size(values)
        spec%target = TARGET_FORTRAN_CPU
        spec%generator = str('gen/gen_hpd_leaves.f90')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen/regenerate_hpd.sh /path/to/fortsym')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%name = str('hpd_'//name//'_value')
        allocate (spec%args(n), spec%outputs(m))
        do i = 1, n
            write (s, '(i0)') i
            spec%args(i) = str('x'//trim(s))
        end do
        do j = 1, m
            write (s, '(i0)') j
            spec%outputs(j) = str('v'//trim(s))
            do i = 1, n
                gradient(i, j) = simplified(diff(values(j), x(i)))
            end do
        end do
        write (u, '(a)') chars(emit_kernel(values, spec))
        deallocate (spec%args, spec%outputs)
        spec%name = str('hpd_'//name//'_jvp')
        allocate (spec%args(2*n), spec%outputs(2*m))
        do i = 1, n
            write (s, '(i0)') i
            spec%args(i) = str('x'//trim(s))
            spec%args(n + i) = str('dx'//trim(s))
        end do
        do j = 1, m
            write (s, '(i0)') j
            spec%outputs(j) = str('v'//trim(s))
            spec%outputs(m + j) = str('dv'//trim(s))
            roots(j) = values(j)
            tangent = gradient(1, j)*dx(1)
            do i = 2, n
                tangent = tangent + gradient(i, j)*dx(i)
            end do
            roots(m + j) = simplified(tangent)
        end do
        write (u, '(a)') chars(emit_kernel(roots, spec))
        deallocate (spec%args, spec%outputs)
        spec%name = str('hpd_'//name//'_vjp')
        allocate (spec%args(n + m), spec%outputs(n + m))
        do j = 1, m
            write (s, '(i0)') j
            spec%args(n + j) = str('s'//trim(s))
            spec%outputs(j) = str('v'//trim(s))
            vjp(j) = values(j)
        end do
        do i = 1, n
            write (s, '(i0)') i
            spec%args(i) = str('x'//trim(s))
            spec%outputs(m + i) = str('bar'//trim(s))
            tangent = gradient(i, 1)*seeds(1)
            do j = 2, m
                tangent = tangent + gradient(i, j)*seeds(j)
            end do
            vjp(m + i) = simplified(tangent)
        end do
        write (u, '(a)') chars(emit_kernel(vjp, spec))
    end subroutine leaf

    function simplified(e) result(s)
        type(expr_t), intent(in) :: e
        type(expr_t) :: s
        type(engine_result_t) :: result
        result = engine%simplify(e)
        if (.not. result%ok) error stop 'FortSym HPD simplification failed'
        s = result%value
    end function simplified
end program gen_hpd_leaves
