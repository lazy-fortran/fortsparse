program gen_spd_leaves
    ! Authoritative local SPD mathematics. Domain: root a>0, divide b/=0.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(-), &
        operator(*), operator(/)
    use fortsym_diff, only: diff
    use fortsym_string, only: str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel, &
        TARGET_FORTRAN_CPU
    use fortsym_kernel_ir, only: kernel_ir_t, lower_kernel_ir
    use fortsym_kernel_emit, only: kernel_emit_spec_t, emit_cuda_device_ir
    use fortsym_string, only: str_t
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    implicit none
    character(*), parameter :: revision = &
        '1372fbd1e8dd2f072ed34a0f82eef60dc68d74cd'
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: a, b, c, da, db, dc, seed
    integer :: unit, cuda, template, ios
    character(256) :: line

    call arena%init()
    engine = make_native_engine(arena)
    a = sym(arena, 'a')
    b = sym(arena, 'b')
    c = sym(arena, 'c')
    da = sym(arena, 'da')
    db = sym(arena, 'db')
    dc = sym(arena, 'dc')
    seed = sym(arena, 'seed')
    open(newunit=unit, file='src/generated/fortsparse_spd_leaves.f90', &
        status='replace', action='write')
    open(newunit=cuda, file='src/generated/fortsparse_spd_leaves.cuh', &
        status='replace', action='write')
    write(unit, '(a)') '! Generated by gen/gen_spd_leaves.f90; DO NOT EDIT.'
    write(unit, '(a)') '! FortSym '//revision
    write(unit, '(a)') 'module fortsparse_spd_leaves'
    write(unit, '(a)') '    use, intrinsic :: iso_fortran_env, only: dp => real64'
    write(unit, '(a)') '    implicit none'
    write(unit, '(a)') '    private'
    write(unit, '(a)') '    public :: spd_root, spd_divide, spd_update'
    write(unit, '(a)') '    public :: spd_root_jvp, spd_divide_jvp, spd_update_jvp'
    write(unit, '(a)') '    public :: spd_root_vjp, spd_divide_vjp, spd_update_vjp'
    write(unit, '(a)') '    public :: spd_panel_factor, spd_panel_solve, spd_schur_update'
    write(unit, '(a)') 'contains'
    write(cuda, '(a)') '// Generated by gen/gen_spd_leaves.f90; DO NOT EDIT.'
    write(cuda, '(a)') '// FortSym '//revision
    write(cuda, '(a)') '#pragma once'
    write(cuda, '(a)') '#include <cmath>'
    call leaf('root', sqrt(a), [a], [da])
    call leaf('divide', a/b, [a, b], [da, db])
    call leaf('update', a-b*c, [a, b, c], [da, db, dc])
    open(newunit=template, file='gen/spd_schedule.f90.inc', action='read')
    do
        read(template, '(a)', iostat=ios) line
        if (ios /= 0) exit
        write(unit, '(a)') trim(line)
    end do
    close(template)
    write(unit, '(a)') 'end module fortsparse_spd_leaves'
    close(unit)
    close(cuda)
contains
    subroutine leaf(name, f, x, dx)
        character(*), intent(in) :: name
        type(expr_t), intent(in) :: f, x(:), dx(:)
        type(expr_t) :: tangent, gradient(size(x)), roots(size(x)+1)
        type(kernel_spec_t) :: spec
        integer :: i
        character(:), allocatable :: args, declarations

        spec%name = str('spd_'//name//'_value')
        spec%generator = str('gen/gen_spd_leaves.f90')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen/regenerate_spd.sh /path/to/fortsym')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        allocate(spec%args(size(x)), spec%outputs(1))
        do i = 1, size(x)
            spec%args(i) = str(symbol_name(i))
        end do
        spec%outputs(1) = str('value')
        call emit([f], spec)
        args = 'a'
        if (size(x) >= 2) args = args//',b'
        if (size(x) == 3) args = args//',c'
        declarations = '        real(dp), intent(in) :: '//args
        write(unit, '(a)') '    pure elemental function spd_'//name//'('//args//') result(value)'
        write(unit, '(a)') declarations
        write(unit, '(a)') '        real(dp) :: value'
        write(unit, '(a)') '        call spd_'//name//'_value('//args//',value)'
        write(unit, '(a)') '    end function spd_'//name

        do i = 1, size(x)
            gradient(i) = simplified(diff(f, x(i)))
        end do
        tangent = gradient(1)*dx(1)
        do i = 2, size(x)
            tangent = tangent+gradient(i)*dx(i)
        end do
        deallocate(spec%args, spec%outputs)
        allocate(spec%args(2*size(x)), spec%outputs(2))
        do i = 1, size(x)
            spec%args(i) = str(symbol_name(i))
            spec%args(size(x)+i) = str('d'//symbol_name(i))
        end do
        spec%name = str('spd_'//name//'_jvp')
        spec%outputs = [str('value'), str('tangent')]
        call emit([f, simplified(tangent)], spec)

        deallocate(spec%args, spec%outputs)
        allocate(spec%args(size(x)+1), spec%outputs(size(x)+1))
        do i = 1, size(x)
            spec%args(i) = str(symbol_name(i))
            spec%outputs(i+1) = str(symbol_name(i)//'bar')
            roots(i+1) = simplified(seed*gradient(i))
        end do
        spec%args(size(x)+1) = str('seed')
        spec%outputs(1) = str('value')
        roots(1) = f
        spec%name = str('spd_'//name//'_vjp')
        call emit(roots, spec)
    end subroutine leaf

    subroutine emit(roots, spec)
        type(expr_t), intent(in) :: roots(:)
        type(kernel_spec_t), intent(inout) :: spec
        type(kernel_ir_t) :: ir
        type(kernel_emit_spec_t) :: cuda_spec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        spec%target = TARGET_FORTRAN_CPU
        write(unit, '(a)') chars(emit_kernel(roots, spec))
        call lower_kernel_ir(roots, ir, ok, message)
        if (.not. ok) error stop message
        cuda_spec%name = spec%name
        cuda_spec%args = spec%args
        cuda_spec%outputs = spec%outputs
        cuda_spec%generator = spec%generator
        cuda_spec%regenerate_command = spec%regenerate_command
        source = emit_cuda_device_ir(ir, cuda_spec, ok, message)
        if (.not. ok) error stop message
        write(cuda, '(a)') chars(source)
    end subroutine emit

    function simplified(e) result(s)
        type(expr_t), intent(in) :: e
        type(expr_t) :: s
        type(engine_result_t) :: result
        result = engine%simplify(e)
        if (.not. result%ok) error stop 'FortSym declined derivative simplification'
        s = result%value
    end function simplified

    function symbol_name(i) result(name)
        integer, intent(in) :: i
        character(:), allocatable :: name
        name = achar(iachar('a')+i-1)
    end function symbol_name
end program gen_spd_leaves
