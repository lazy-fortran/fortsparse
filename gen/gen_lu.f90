program gen_lu
    ! Continuous complex arithmetic is Cartesian with the ordinary real
    ! component pairing. Indexed factor/solve schedules are retained separately.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t,sym,operator(+),operator(-),operator(*),operator(/)
    use fortsym_diff, only: diff
    use fortsym_string, only: str,chars
    use fortsym_kernel, only: kernel_spec_t,emit_kernel,TARGET_FORTRAN_CPU
    implicit none
    character(*), parameter :: revision='7e8ef7abdd90c49bb5f75e2c119e7d181656bcc6'
    type(arena_t), target :: arena
    type(expr_t) :: x(6),dx(6),seed(2),f(2),denominator
    integer :: unit,i
    call arena%init()
    do i=1,6
        x(i)=sym(arena,'x'//digit(i))
        dx(i)=sym(arena,'d'//digit(i))
    end do
    seed(1)=sym(arena,'s1')
    seed(2)=sym(arena,'s2')
    open(newunit=unit,file='src/generated/fortsparse_lu_leaves.f90',status='replace')
    write(unit,'(a)') '! Generated by gen/gen_lu.f90; DO NOT EDIT.'
    write(unit,'(a)') '! FortSym '//revision
    write(unit,'(a)') 'module fortsparse_lu_leaves'
    write(unit,'(a)') '    use fortsparse_kinds, only: dp'
    write(unit,'(a)') '    use, intrinsic :: ieee_arithmetic, only: ieee_is_finite'
    write(unit,'(a)') '    implicit none'
    write(unit,'(a)') '    private'
    write(unit,'(a)') '    public :: lu_z_update, lu_z_divide, lu_z_norm, lu_z_finite'
    write(unit,'(a)') '    public :: lu_z_update_value, lu_z_update_jvp, lu_z_update_vjp'
    write(unit,'(a)') '    public :: lu_z_quotient_value, lu_z_quotient_jvp, lu_z_quotient_vjp'
    write(unit,'(a)') 'contains'
    f=[x(1)-x(3)*x(5)+x(4)*x(6),x(2)-x(3)*x(6)-x(4)*x(5)]
    call leaf('update',6)
    denominator=x(3)*x(3)+x(4)*x(4)
    f=[(x(1)*x(3)+x(2)*x(4))/denominator,(x(2)*x(3)-x(1)*x(4))/denominator]
    call leaf('quotient',4)
    call copy('gen/lu_complex_schedule.f90.inc',unit)
    write(unit,'(a)') 'end module fortsparse_lu_leaves'
    close(unit)
    open(newunit=unit,file='src/native/fortsparse_native_lu.f90',status='replace')
    call schedule(.false.)
    call schedule(.true.)
    close(unit)
contains
    function digit(i) result(s)
        integer, intent(in) :: i
        character(1) :: s
        s=achar(iachar('0')+i)
    end function digit
    subroutine leaf(name,n)
        character(*), intent(in) :: name
        integer, intent(in) :: n
        type(kernel_spec_t) :: spec
        type(expr_t) :: tangent(2),pullback(2+n),jacobian(2,n)
        integer :: i,j
        spec%target=TARGET_FORTRAN_CPU
        spec%generator=str('gen/gen_lu.f90')
        spec%generator_revision=str(revision)
        spec%regenerate_command=str('gen/regenerate_lu.sh /path/to/fortsym')
        spec%pure_procedure=.true.
        spec%elemental_procedure=.true.
        allocate(spec%args(n),spec%outputs(2))
        do i=1,n
            spec%args(i)=str('x'//digit(i))
            do j=1,2
                jacobian(j,i)=diff(f(j),x(i))
            end do
        end do
        spec%outputs=[str('vr'),str('vi')]
        spec%name=str('lu_z_'//name//'_value')
        write(unit,'(a)') chars(emit_kernel(f,spec))
        deallocate(spec%args,spec%outputs)
        allocate(spec%args(2*n),spec%outputs(4))
        do i=1,n
            spec%args(i)=str('x'//digit(i))
            spec%args(n+i)=str('d'//digit(i))
        end do
        do j=1,2
            tangent(j)=jacobian(j,1)*dx(1)
            do i=2,n
                tangent(j)=tangent(j)+jacobian(j,i)*dx(i)
            end do
        end do
        spec%outputs=[str('vr'),str('vi'),str('dr'),str('di')]
        spec%name=str('lu_z_'//name//'_jvp')
        write(unit,'(a)') chars(emit_kernel([f,tangent],spec))
        deallocate(spec%args,spec%outputs)
        allocate(spec%args(n+2),spec%outputs(n+2))
        pullback(:2)=f
        spec%outputs(1)=str('vr')
        spec%outputs(2)=str('vi')
        do i=1,n
            spec%args(i)=str('x'//digit(i))
            spec%outputs(i+2)=str('b'//digit(i))
            pullback(i+2)=seed(1)*jacobian(1,i)+seed(2)*jacobian(2,i)
        end do
        spec%args(n+1)=str('s1')
        spec%args(n+2)=str('s2')
        spec%name=str('lu_z_'//name//'_vjp')
        write(unit,'(a)') chars(emit_kernel(pullback,spec))
    end subroutine leaf
    subroutine copy(path,out)
        character(*), intent(in) :: path
        integer, intent(in) :: out
        integer :: input,ios
        character(1024) :: line
        open(newunit=input,file=path,status='old')
        do
            read(input,'(a)',iostat=ios) line
            if (ios/=0) exit
            write(out,'(a)') trim(line)
        end do
        close(input)
    end subroutine copy
    function replace(s,key,value) result(out)
        character(*), intent(in) :: s,key,value
        character(:), allocatable :: out
        integer :: p
        out=s
        do
            p=index(out,key)
            if (p==0) exit
            out=out(:p-1)//value//out(p+len(key):)
        end do
    end function replace
    subroutine schedule(z)
        logical, intent(in) :: z
        character(:), allocatable :: line,name,kind,scalar,csc,leaves,update,divide,extra,finite,norm,zero,adjoint
        character(1024) :: buffer
        character(8), parameter :: arrays(*)=[character(8) :: &
            'lp','up','lr','ur','p','pinv','q','ap','ai','mark','stack','edge','reach','lv','uv','work','row_norm']
        integer :: input,ios,i
        name='fortsparse_native_lu'; kind='lu_factor_t'; scalar='real(dp)'; csc='csc_t'
        leaves='fortsparse_spd_leaves';update='spd_update';divide='spd_divide'
        extra='';finite='ieee_is_finite';norm='abs';zero='0.0_dp';adjoint='a'
        if(z) then
            name=name//'_z';kind='lu_factor_z_t';scalar='complex(dp)';csc='csc_z_t'
            leaves='fortsparse_lu_leaves';update='lu_z_update';divide='lu_z_divide'
            extra='use fortsparse_lu_leaves, only: lu_z_finite, lu_z_norm'
            finite='lu_z_finite';norm='lu_z_norm';zero='(0.0_dp,0.0_dp)';adjoint='conjg(a)'
        end if
        open(newunit=input,file='gen/lu_factor.f90.inc',status='old')
        do
            read(input,'(a)',iostat=ios) buffer
            if(ios/=0) exit
            line=trim(buffer)
            if(line=='@MEMORY@'.or.line=='@FREE@') then
                do i=1,size(arrays)
                    if(line=='@FREE@') then
                        write(unit,'(a)') '        if(allocated(self%'//trim(arrays(i))//')) deallocate(self%'//trim(arrays(i))//')'
                    else if(i<=13) then
                        write(unit,'(a)') '        if(allocated(self%'//trim(arrays(i))// &
                            ')) bytes=bytes+ib*size(self%'//trim(arrays(i))//',kind=i8)'
                    else if(i<=16) then
                        write(unit,'(a)') '        if(allocated(self%'//trim(arrays(i))// &
                            ')) bytes=bytes+vb*size(self%'//trim(arrays(i))//',kind=i8)'
                    else
                        write(unit,'(a)') '        if(allocated(self%row_norm)) bytes=bytes+8_i8*size(self%row_norm,kind=i8)'
                    end if
                end do
                cycle
            end if
            line=replace(line,'@MODULE@',name);line=replace(line,'@TYPE@',kind)
            line=replace(line,'@CSC@',csc);line=replace(line,'@SCALAR@',scalar)
            line=replace(line,'@LEAVES@',leaves);line=replace(line,'@UPDATE@',update)
            line=replace(line,'@DIVIDE@',divide);line=replace(line,'@EXTRA_USE@',extra)
            line=replace(line,'@FINITE@',finite);line=replace(line,'@NORM@',norm)
            line=replace(line,'@ZERO@',zero);line=replace(line,'@ADJOINT@',adjoint)
            if(z) then
                line=replace(line,'@VALUE_BYTES@','16')
            else
                line=replace(line,'@VALUE_BYTES@','8')
            end if
            if(index(line,'@')/=0) error stop 'unexpanded LU schedule token'
            write(unit,'(a)') trim(line)
        end do
        close(input)
    end subroutine schedule
end program gen_lu
