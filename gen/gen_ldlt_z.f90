program gen_ldlt_z
    ! Real-component source for complex block determinants/numerators and
    ! rank-two updates. Division and power-of-two scaling reuse LU leaves.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*)
    use fortsym_diff, only: diff
    use fortsym_string, only: str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel, TARGET_FORTRAN_CPU
    implicit none
    character(*), parameter :: revision = &
                               '7e8ef7abdd90c49bb5f75e2c119e7d181656bcc6'
    type(arena_t), target :: arena
    type(expr_t) :: x(12), dx(12), seed(4), f(4)
    integer :: unit, i
    call arena%init()
    do i = 1, 12
        x(i) = sym(arena, name('x', i))
        dx(i) = sym(arena, name('d', i))
    end do
    do i = 1, 4
        seed(i) = sym(arena, name('s', i))
    end do
    open (newunit=unit, file='src/generated/fortsparse_ldlt_z_leaves.f90', &
          status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_ldlt_z.f90; DO NOT EDIT.'
    write (unit, '(a)') '! FortSym '//revision
    write (unit, '(a)') 'module fortsparse_ldlt_z_leaves'
    write (unit, '(a)') '    use, intrinsic :: iso_fortran_env, only: dp => real64'
    write (unit, '(a)') '    implicit none'
    write (unit, '(a)') 'contains'
    ! D=[[a,b],[d,c]]; no assumption d=b or conjg(b) in the generic leaf.
    ! Inputs: a=x1:2, b=x3:4, d=x5:6, c=x7:8, u=x9:10, v=x11:12.
    f(:2) = difference(product(x(:2), x(7:8)), product(x(3:4), x(5:6)))
    call leaf('det', 8, 2)
    f(:2) = difference(product(x(7:8), x(9:10)), product(x(5:6), x(11:12)))
    f(3:4) = difference(product(x(:2), x(11:12)), product(x(3:4), x(9:10)))
    call leaf('numerators', 12, 4)
    f(:2) = difference(difference(x(:2), product(x(3:4), x(5:6))), &
                       product(x(7:8), x(9:10)))
    call leaf('update', 10, 2)
    call copy('gen/ldlt_z_leaves.f90.inc', unit)
    write (unit, '(a)') 'end module fortsparse_ldlt_z_leaves'
    close (unit)
    open (newunit=unit, file='src/native/fortsparse_native_ldlt_z.f90', &
          status='replace', action='write')
    write (unit, '(a)') '! Generated indexed schedule from gen/ldlt_z_factor.f90.inc.'
    write (unit, '(a)') '! DO NOT EDIT; regenerate with gen/regenerate_ldlt_z.sh.'
    call copy('gen/ldlt_z_factor.f90.inc', unit)
    close (unit)
contains
    function name(prefix, i) result(s)
        character(*), intent(in) :: prefix
        integer, intent(in) :: i
        character(:), allocatable :: s
        character(12) :: number
        write (number, '(i0)') i
        s = prefix//trim(number)
    end function name
    function product(a, b) result(z)
        type(expr_t), intent(in) :: a(2), b(2)
        type(expr_t) :: z(2)
        z = [a(1)*b(1) - a(2)*b(2), a(1)*b(2) + a(2)*b(1)]
    end function product
    function difference(a, b) result(z)
        type(expr_t), intent(in) :: a(2), b(2)
        type(expr_t) :: z(2)
        z = [a(1) - b(1), a(2) - b(2)]
    end function difference
    subroutine leaf(label, n, m)
        character(*), intent(in) :: label
        integer, intent(in) :: n, m
        type(kernel_spec_t) :: spec
        type(expr_t) :: tangent(m), pullback(m + n), jacobian(m, n)
        integer :: i, j
        spec%target = TARGET_FORTRAN_CPU
        spec%generator = str('gen/gen_ldlt_z.f90')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen/regenerate_ldlt_z.sh /path/to/fortsym')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        allocate (spec%args(n), spec%outputs(m))
        do i = 1, n
            spec%args(i) = str(name('x', i))
            do j = 1, m
                jacobian(j, i) = diff(f(j), x(i))
            end do
        end do
        do j = 1, m
            spec%outputs(j) = str(name('v', j))
        end do
        spec%name = str('ldlt_z_'//label//'_value')
        write (unit, '(a)') chars(emit_kernel(f(:m), spec))
        deallocate (spec%args, spec%outputs)
        allocate (spec%args(2*n), spec%outputs(2*m))
        do i = 1, n
            spec%args(i) = str(name('x', i))
            spec%args(n + i) = str(name('d', i))
        end do
        do j = 1, m
            tangent(j) = jacobian(j, 1)*dx(1)
            do i = 2, n
                tangent(j) = tangent(j) + jacobian(j, i)*dx(i)
            end do
            spec%outputs(j) = str(name('v', j))
            spec%outputs(m + j) = str(name('tangent_', j))
        end do
        spec%name = str('ldlt_z_'//label//'_jvp')
        write (unit, '(a)') chars(emit_kernel([f(:m), tangent], spec))
        deallocate (spec%args, spec%outputs)
        allocate (spec%args(n + m), spec%outputs(n + m))
        pullback(:m) = f(:m)
        do j = 1, m
            spec%outputs(j) = str(name('v', j))
            spec%args(n + j) = str(name('s', j))
        end do
        do i = 1, n
            spec%args(i) = str(name('x', i))
            spec%outputs(m + i) = str(name('b', i))
            pullback(m + i) = seed(1)*jacobian(1, i)
            do j = 2, m
                pullback(m + i) = pullback(m + i) + seed(j)*jacobian(j, i)
            end do
        end do
        spec%name = str('ldlt_z_'//label//'_vjp')
        write (unit, '(a)') chars(emit_kernel(pullback, spec))
    end subroutine leaf
    subroutine copy(path, out)
        character(*), intent(in) :: path
        integer, intent(in) :: out
        integer :: input, ios
        character(1024) :: line
        open (newunit=input, file=path, status='old')
        do
            read (input, '(a)', iostat=ios) line
            if (ios /= 0) exit
            write (out, '(a)') trim(line)
        end do
        close (input)
    end subroutine copy
end program gen_ldlt_z
