program gen_slu_leaves
    ! Authoritative scalar mathematics of the static-structure supernodal LU.
    ! Value leaves only: derivatives differentiate the solve equation, never
    ! the factorization (docs/lu-supernodal.md, section 8). The indexed
    ! diagonal-block, triangular, Schur and solve schedules are retained in
    ! gen/slu_schedule.f90.inc and call only these leaves. The complex twin
    ! (fortsparse_slu_z_leaves) emits the same three definitions in Cartesian
    ! real components with gen/slu_z_schedule.f90.inc.
    ! Domains: divide requires b /= 0 (perturbed pivots guarantee it).
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*), &
        operator(/)
    use fortsym_string, only: str
    use fortsym_kernel, only: kernel_spec_t, emit_kernel, TARGET_FORTRAN_CPU
    use fortsym_string, only: chars
    implicit none
    character(*), parameter :: revision = &
        '7e8ef7abdd90c49bb5f75e2c119e7d181656bcc6'
    type(arena_t), target :: arena
    type(expr_t) :: a, b, c, z(6), f(2)
    integer :: unit, template, ios
    character(512) :: line

    call arena%init()
    a = sym(arena, 'a')
    b = sym(arena, 'b')
    c = sym(arena, 'c')
    open(newunit=unit, file='src/generated/fortsparse_slu_leaves.f90', &
        status='replace', action='write')
    write(unit, '(a)') '! Generated by gen/gen_slu_leaves.f90; DO NOT EDIT.'
    write(unit, '(a)') '! FortSym '//revision
    write(unit, '(a)') 'module fortsparse_slu_leaves'
    write(unit, '(a)') '    use, intrinsic :: iso_fortran_env, only: dp => real64'
    write(unit, '(a)') '    implicit none'
    write(unit, '(a)') '    private'
    write(unit, '(a)') '    public :: slu_update, slu_divide, slu_scale'
    write(unit, '(a)') &
        '    public :: slu_block_factor, slu_trsm_upper, slu_trsm_unit_lower_t'
    write(unit, '(a)') '    public :: slu_panel_factor, slu_schur_update, slu_apply_swaps'
    write(unit, '(a)') '    public :: slu_block_lower, slu_block_upper'
    write(unit, '(a)') '    public :: slu_block_upper_t, slu_block_lower_t'
    write(unit, '(a)') 'contains'
    call leaf('update', a-b*c, [a, b, c])
    call leaf('divide', a/b, [a, b])
    call leaf('scale', a*b*c, [a, b, c])
    open(newunit=template, file='gen/slu_schedule.f90.inc', action='read')
    do
        read(template, '(a)', iostat=ios) line
        if (ios /= 0) exit
        write(unit, '(a)') trim(line)
    end do
    close(template)
    write(unit, '(a)') 'end module fortsparse_slu_leaves'
    close(unit)
    call complex_module()
contains
    subroutine complex_module()
        ! Inputs ar, ai, br, bi, cr, ci with the ordinary component pairing.
        character(2), parameter :: names(6) = ['ar', 'ai', 'br', 'bi', 'cr', 'ci']
        type(expr_t) :: denominator
        integer :: i
        do i = 1, 6
            z(i) = sym(arena, names(i))
        end do
        open(newunit=unit, file='src/generated/fortsparse_slu_z_leaves.f90', &
            status='replace', action='write')
        write(unit, '(a)') '! Generated by gen/gen_slu_leaves.f90; DO NOT EDIT.'
        write(unit, '(a)') '! FortSym '//revision
        write(unit, '(a)') 'module fortsparse_slu_z_leaves'
        write(unit, '(a)') '    use, intrinsic :: iso_fortran_env, only: dp => real64'
        write(unit, '(a)') '    implicit none'
        write(unit, '(a)') '    private'
        write(unit, '(a)') '    public :: slu_z_update, slu_z_divide, slu_z_scale'
        write(unit, '(a)') '    public :: slu_z_block_factor, slu_z_trsm_upper'
        write(unit, '(a)') '    public :: slu_z_trsm_unit_lower_t, slu_z_schur_update'
        write(unit, '(a)') '    public :: slu_z_apply_swaps, slu_z_block_lower'
        write(unit, '(a)') '    public :: slu_z_block_upper, slu_z_block_upper_t'
        write(unit, '(a)') '    public :: slu_z_block_lower_t, slu_z_scatter_mapped_update'
        write(unit, '(a)') '    public :: slu_z_scatter_update, slu_z_gather_update'
        write(unit, '(a)') 'contains'
        ! a - b*c
        f = [z(1)-(z(3)*z(5)-z(4)*z(6)), z(2)-(z(3)*z(6)+z(4)*z(5))]
        call complex_leaf('update', names)
        ! a/b; the schedule normalizes a and b by powers of two first.
        denominator = z(3)*z(3)+z(4)*z(4)
        f = [(z(1)*z(3)+z(2)*z(4))/denominator, (z(2)*z(3)-z(1)*z(4))/denominator]
        call complex_leaf('quotient', names(1:4))
        ! a*b*c with real scales a = ar and c = cr.
        f = [z(1)*z(3)*z(5), z(1)*z(4)*z(5)]
        call complex_leaf('scale', ['ar', 'br', 'bi', 'cr'])
        open(newunit=template, file='gen/slu_z_schedule.f90.inc', action='read')
        do
            read(template, '(a)', iostat=ios) line
            if (ios /= 0) exit
            write(unit, '(a)') trim(line)
        end do
        close(template)
        write(unit, '(a)') 'end module fortsparse_slu_z_leaves'
        close(unit)
    end subroutine complex_module

    subroutine complex_leaf(name, args)
        character(*), intent(in) :: name
        character(2), intent(in) :: args(:)
        type(kernel_spec_t) :: spec
        integer :: i
        spec%target = TARGET_FORTRAN_CPU
        spec%name = str('slu_z_'//name//'_value')
        spec%generator = str('gen/gen_slu_leaves.f90')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen/regenerate_slu.sh /path/to/fortsym')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        allocate(spec%args(size(args)), spec%outputs(2))
        do i = 1, size(args)
            spec%args(i) = str(args(i))
        end do
        spec%outputs(1) = str('vr')
        spec%outputs(2) = str('vi')
        write(unit, '(a)') chars(emit_kernel(f, spec))
    end subroutine complex_leaf

    subroutine leaf(name, f, x)
        character(*), intent(in) :: name
        type(expr_t), intent(in) :: f, x(:)
        type(kernel_spec_t) :: spec
        character(:), allocatable :: args
        character(1), parameter :: names(3) = ['a', 'b', 'c']
        integer :: i

        spec%target = TARGET_FORTRAN_CPU
        spec%name = str('slu_'//name//'_value')
        spec%generator = str('gen/gen_slu_leaves.f90')
        spec%generator_revision = str(revision)
        spec%regenerate_command = str('gen/regenerate_slu.sh /path/to/fortsym')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        allocate(spec%args(size(x)), spec%outputs(1))
        args = names(1)
        spec%args(1) = str(names(1))
        do i = 2, size(x)
            spec%args(i) = str(names(i))
            args = args//','//names(i)
        end do
        spec%outputs(1) = str('value')
        write(unit, '(a)') chars(emit_kernel([f], spec))
        write(unit, '(a)') '    pure elemental function slu_'//name//'('//args// &
            ') result(value)'
        write(unit, '(a)') '        real(dp), intent(in) :: '//args
        write(unit, '(a)') '        real(dp) :: value'
        write(unit, '(a)') '        call slu_'//name//'_value('//args//',value)'
        write(unit, '(a)') '    end function slu_'//name
    end subroutine leaf
end program gen_slu_leaves
